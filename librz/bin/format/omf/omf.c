static int load_comment_data(const rz_bin_omf_obj *obj, const ut8 *buf, const OMF_record *record, ut64 buf_size) {
	if (!(obj && obj->coments_vec)) {
		return false;
	}

	OMF_coments *comment = RZ_NEW0(OMF_coments);
	if (!comment) {
		return false;
	}

	size_t ct = 3;
	const ut8 comment_type = rz_read_le8_offset(buf, &ct);
	const ut8 comment_class = rz_read_le8_offset(buf, &ct);

	/**
	 * NP (no purge bit) is set if the comment is to be preserved by
	 * utility programs that manipulate object modules.
	 * This bit can protect an important comment, such as a copyright message, from deletion
	**/
	comment->nopurge = (comment_type & 0x80) >> 7; // Or (comment_type & 0x80) >> 7;
	comment->is_filename = (comment_type == 0x4b);
	comment->n = record->size + 3 - ct;
	rz_mem_copy(comment->text, MAX_NAME_LEN, buf + ct, comment->n);
	rz_pvector_push(obj->coments_vec, comment);
	// return true;



	printf("0x%02x   0x%02x 0x%02x   ",	buf[0], buf[1], buf[2]);
	rz_print_bytes(NULL, buf + 3, record->size, "0x%02x ");


	/**
	 * NL (no list bit) is set if the comment is not to be displayed by
	 * utility programs that list the contents of object modules.
	 * This bit can hide a comment.
	**/
	const bool NL = (comment_type & 0x40) >> 6;
	printf("nopurge: %s, NL: %s, comment_type: 0x%02x, comment_class: 0x%02x `%s` ct: %lu\n",
		comment->nopurge ? "true" : "false", NL ? "true" : "false", comment_type, comment_class, type_desc(comment_class), ct);

	if (record->size - 3 > 0) {
		rz_print_bytes(NULL, buf + ct, record->size - 3, "0x%02x ");
		// char Commentary_Byte_String[MAX_NAME_LEN] = { 0 };

		if (comment_class == 0xe9) {
			if (record->size > ct + 4) {
				const ut32 tm = rz_read_le32_offset(buf, &ct);

				char buffer[80];
				const time_t raw_time = (time_t)tm;
				const struct tm *time_info = localtime(&raw_time); // Convert to local time structure
				strftime(buffer, sizeof(buffer), "%Y-%m-%d %H:%M:%S", time_info);

				char name[MAX_NAME_LEN] = { 0 };
				const ut8 n = rz_read_le8_offset(buf, &ct);
				if (ct + n + 1 > buf_size) {
					RZ_LOG_ERROR("Invalid record (overflow)\n");
					return true;
				}
				rz_mem_copy(name, MAX_NAME_LEN, buf + ct, n);
				printf("\t\t[ %s ] %u name: `%s` size: %d\n",	buffer, tm, name, n);
				// RZ_LOG_ERROR("Invalid record (overflow)\n");
			}
		}
	}
	return true;
}

static int load_linnum_data(const rz_bin_omf_obj *obj, const ut8 *buf, const size_t buf_size, const OMF_record *record) {
	OMF_linnums *linnum = NULL;
	size_t ct = 3;

	const ut8 GroupIndex = omf_get_idx(buf + ct, buf_size - ct); // ct = 3
	ct++;
	const ut8 SectionIndex = omf_get_idx(buf + ct, buf_size - ct); // ct = 4
	ct++;
	ut16 FrameNumber = 0x00;
	if (!GroupIndex && !SectionIndex) {
		FrameNumber = rz_read_le16_offset(buf, &ct);
	}

	while (ct < record->size) {
		linnum = RZ_NEW0(OMF_linnums);
		if (!linnum) {
			return false;
		}
		linnum->LineNumber = rz_read_le16_offset(buf, &ct); // start with ct = 5
		const ut16 offset = rz_read_le16_offset(buf, &ct);
		linnum->address = ((ut64)FrameNumber << 16) | offset;
		const OMF_coments *comment = rz_pvector_tail(obj->coments_vec);
		if (!comment) {
			RZ_FREE(linnum);
			return false;
		}
		linnum->n = comment->n;
		rz_str_ncpy(linnum->filename, comment->text, comment->n);
		rz_pvector_push(obj->linnums_vec, linnum);
	}
	return true;
}

static ut32 omf_count_symb(ut16 total_size, ut32 ct, const ut8 *buf, int bits) {
	ut32 nb_symb = 0;
	while (ct < total_size - 1) {
		ct += buf[ct] + 1 + (bits == 32 ? 4 : 2);
		if (ct > total_size - 1) {
			return nb_symb;
		}
		if (buf[ct] & 0x80) {
			ct += 2;
		} else {
			ct++;
		}
		nb_symb++;
	}
	return nb_symb;
}

static int load_omf_symb(const OMF_record *record, ut32 ct, const ut8 *buf, const ut64 buf_size, int bits, ut16 seg_idx) {
	ut32 nb_symb = 0;
	ut8 str_size = 0;

	while (nb_symb < ((OMF_multi_datas *)record->content)->nb_elem) {
		OMF_symbol *symbol = ((OMF_symbol *)((OMF_multi_datas *)record->content)->elems) + nb_symb;

		if (record->size - 1 < ct - 2) {
			RZ_LOG_ERROR("Invalid Pubdef record (bad size)\n");
			return false;
		}
		str_size = buf[ct];
		if (str_size == 0 || str_size > UT8_MAX) {
			RZ_LOG_ERROR("Invalid Pubdef record (bad size)\n");
			return false;
		}

		if (bits == 32) {
			if (ct + 1 + str_size + 4 - 3 > record->size) {
				RZ_LOG_ERROR("Invalid Pubdef record (bad size)\n");
				return false;
			}
			symbol->offset = rz_read_le32(buf + ct + 1 + str_size);
		} else {
			if (ct + 1 + str_size + 2 - 3 > record->size) {
				RZ_LOG_ERROR("Invalid Pubdef record (bad size)\n");
				return false;
			}
			symbol->offset = rz_read_le16(buf + ct + 1 + str_size);
		}

		symbol->seg_idx = seg_idx;
		symbol->name = RZ_NEWS0(char, str_size + 1);
		if (!symbol->name) {
			return false;
		}
		symbol->name[str_size] = 0;
		memcpy(symbol->name, buf + ct + 1, sizeof(char) * str_size);

		ct += 1 + str_size + (bits == 32 ? 4 : 2);
		if (ct >= buf_size) {
			free(symbol->name);
			return false;
		}
		if (buf[ct] & 0x80) { // type index
			ct += 2;
		} else {
			ct++;
		}
		nb_symb++;
	}
	return true;
}

static int load_omf_pubdef(OMF_record *record, const ut8 *buf, const ut64 buf_size) {
	OMF_multi_datas *ret = NULL;
	ut16 ct = 0;

	if (record->size < 2) {
		RZ_LOG_ERROR("Invalid Pubdef record (bad size)\n");
		return false;
	}

	ct = 3;
	const ut16 base_grp = omf_get_idx(buf + ct, buf_size - ct);
	if (buf[ct] & 0x80) { // sizeof base groups index
		ct += 2;
	} else {
		ct++;
	}

	if (record->size < ct - 2) {
		RZ_LOG_ERROR("Invalid Pubdef record (bad size)\n");
		return false;
	}

	const ut16 seg_idx = omf_get_idx(buf + ct, buf_size - ct);

	if (buf[ct] & 0x80) { // sizeof base segment index
		ct += 2;
	} else {
		ct++;
	}

	if (!base_grp && !seg_idx) {
		ct += 2;
	}
	if (record->size < ct - 2) {
		RZ_LOG_ERROR("Invalid Pubdef record (bad size)\n");
		return false;
	}
	ret = RZ_NEW0(OMF_multi_datas);
	if (!ret) {
		return false;
	}
	record->content = ret;

	if (!(record->type & 1)) { // 16 bit addr
		ret->nb_elem = omf_count_symb(record->size + 3, ct, buf, 16);
		if (ret->nb_elem > 0) {
			ret->elems = RZ_NEWS0(OMF_symbol, ret->nb_elem);
			if (!ret->elems) {
				return false;
			}
		}
		if (!load_omf_symb(record, ct, buf, buf_size, 16, seg_idx)) {
			return false;
		}
	} else { // 32 bit addr
		ret->nb_elem = omf_count_symb(record->size + 3, ct, buf, 32);
		if (ret->nb_elem > 0) {
			ret->elems = RZ_NEWS0(OMF_symbol, ret->nb_elem);
			if (!ret->elems) {
				return false;
			}
		}
		if (!load_omf_symb(record, ct, buf, buf_size, 32, seg_idx)) {
			return false;
		}
	}

	// tricks to keep the save index when copying content from record
	record->type = OMF_PUBDEF;
	return true;
}

